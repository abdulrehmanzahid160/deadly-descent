import { chromium, expect } from '@playwright/test'
import fs from 'node:fs/promises'

await fs.mkdir('artifacts', { recursive: true })
const browser = await chromium.launch({ headless: true, ...(process.platform === 'win32' ? { executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' } : {}), args: ['--enable-webgl', '--ignore-gpu-blocklist'] })
const errors = []
const baseURL = process.env.TEST_URL || 'http://127.0.0.1:5174'
async function ready(page) {
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto(`${baseURL}/?test`, { waitUntil: 'networkidle' })
  await page.getByRole('button', { name: 'START YOUR DESCENT' }).waitFor({ timeout: 60000 })
}
const snapshot = page => page.evaluate(() => window.__descent.snapshot())
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  await ready(page)
  expect((await snapshot(page)).detailedCar).toBe(true)
  await page.getByRole('button', { name: 'Glacier paint' }).click()
  await expect(page.getByRole('button', { name: 'Glacier paint' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'GOLDEN HOUR' }).click()
  expect((await snapshot(page)).condition).toBe('golden')
  await page.screenshot({ path: 'artifacts/golden-garage.png' })
  await page.getByRole('button', { name: 'ALPINE MORNING' }).click()
  await page.getByRole('button', { name: 'Rosso paint' }).click()
  await page.getByLabel('Graphics quality').selectOption('medium')
  expect((await snapshot(page)).quality).toBe('medium')
  await page.getByRole('button', { name: 'START YOUR DESCENT' }).click()
  await page.keyboard.down('w')
  await expect.poll(async () => (await snapshot(page)).speed, { timeout: 15000 }).toBeGreaterThan(15)
  await page.keyboard.down('a')
  await expect.poll(async () => (await snapshot(page)).offset, { timeout: 10000 }).toBeLessThan(1.4)
  await page.keyboard.up('a'); await page.keyboard.up('w')
  const preBrake = (await snapshot(page)).speed
  await page.keyboard.down('s')
  await expect.poll(async () => (await snapshot(page)).speed).toBeLessThan(preBrake - 2)
  await page.keyboard.up('s')
  await page.keyboard.press('c'); expect((await snapshot(page)).cameraMode).toBe('hood')
  await page.keyboard.press('c'); expect((await snapshot(page)).cameraMode).toBe('cockpit')
  await page.screenshot({ path: 'artifacts/cockpit.png' })
  await page.keyboard.press('c'); expect((await snapshot(page)).cameraMode).toBe('chase')
  await page.keyboard.press('p')
  await expect(page.getByRole('button', { name: 'BACK TO THE ROAD' })).toBeVisible()
  const paused = (await snapshot(page)).progress
  await page.waitForTimeout(400)
  expect((await snapshot(page)).progress).toBe(paused)
  await page.getByRole('button', { name: 'BACK TO THE ROAD' }).click()
  await page.keyboard.down('w'); await page.keyboard.down('d')
  await expect.poll(async () => (await snapshot(page)).phase, { timeout: 20000 }).toBe('crashed')
  await page.keyboard.up('w'); await page.keyboard.up('d')
  await expect(page.getByText('GUARDRAIL IMPACT', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'DRIVE AGAIN' }).click()
  const restarted = await snapshot(page)
  expect(restarted.phase).toBe('playing'); expect(restarted.progress).toBeLessThan(125); expect(restarted.fuel).toBeGreaterThan(99)
  await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  expect((await snapshot(page)).phase).toBe('paused')
  await page.getByRole('button', { name: 'RETURN TO GARAGE' }).click()
  await expect(page.getByRole('button', { name: 'START YOUR DESCENT' })).toBeVisible()
  console.log('PASS desktop: car, paint, lighting, quality, accelerator, steering, brake, cameras, pause, collision, restart, blur')
  await page.close()

  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 })
  await ready(mobile)
  await mobile.screenshot({ path: 'artifacts/mobile-garage.png' })
  expect(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await mobile.getByRole('button', { name: 'START YOUR DESCENT' }).tap()
  const gas = mobile.getByRole('button', { name: 'GAS ↑' })
  await expect(gas).toBeVisible()
  // Real simultaneous touches, followed by cancellation, catch sticky control regressions.
  const cdp = await mobile.context().newCDPSession(mobile)
  const gasBox = await gas.boundingBox(), leftBox = await mobile.getByRole('button', { name: 'Steer left' }).boundingBox()
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: gasBox.x + gasBox.width / 2, y: gasBox.y + gasBox.height / 2, id: 1 }, { x: leftBox.x + leftBox.width / 2, y: leftBox.y + leftBox.height / 2, id: 2 }] })
  await expect.poll(async () => (await snapshot(mobile)).controls.gas).toBe(true)
  expect((await snapshot(mobile)).controls.steerLeft).toBe(true)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] })
  await expect.poll(async () => (await snapshot(mobile)).controls.gas).toBe(false)
  expect((await snapshot(mobile)).controls.steerLeft).toBe(false)
  await mobile.setViewportSize({ width: 844, height: 390 })
  await mobile.screenshot({ path: 'artifacts/mobile-landscape.png' })
  await expect(gas).toBeVisible()
  await mobile.getByLabel('Graphics quality').selectOption('low')
  expect((await snapshot(mobile)).quality).toBe('low')
  console.log('PASS mobile: portrait and landscape layouts, simultaneous steering/acceleration, touch cancellation, performance mode')
  expect(errors).toEqual([])
  console.log('PASS no browser errors')
} finally { await browser.close() }
